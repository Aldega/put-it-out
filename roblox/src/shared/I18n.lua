-- язык по настройкам игрока: ru, es, иначе en
function I18n.detect(locale)
	local l = string.lower(string.sub(locale or "", 1, 2))
	if l == "ru" or l == "es" then return l end
	return "en"
end

-- перевод с подстановкой {0}, {1}...; русские аргументы тоже переводятся
function I18n.t(lang, s, args)
	if type(s) ~= "string" then return tostring(s) end
	local out = s
	if lang ~= "ru" then
		local d = I18n[lang]
		if d and d[s] then out = d[s] end
	end
	if args then
		for i, a in ipairs(args) do
			local v = a
			if type(a) == "string" then v = I18n.t(lang, a) end
			out = string.gsub(out, "{" .. (i - 1) .. "}", (string.gsub(tostring(v), "%%", "%%%%")))
		end
	end
	return out
end

return I18n
